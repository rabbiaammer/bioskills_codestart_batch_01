# Exercise 3: Student Grader

name = input("Student name: ").strip().title()
marks = input("Marks (0-100): ")

if marks.isdigit():
    marks = int(marks)

    if marks > 100:
        print("Marks must be 0-100")
    else:
        if marks >= 90:
            grade = "A"
        elif marks >= 80:
            grade = "B"
        elif marks >= 70:
            grade = "C"
        elif marks >= 50:
            grade = "D"
        else:
            grade = "F"

        print(f"{name} scored {marks}/100 → Grade {grade}")
else:
    print("Invalid marks")

